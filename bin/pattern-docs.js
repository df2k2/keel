#!/usr/bin/env node
/**
 * Writes docs/patterns.md from the headers of every file in patterns/: one table per category
 * with title, slug, keywords and template types, so the list never drifts from the code.
 *
 * Usage: node bin/pattern-docs.js
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CATEGORIES } from './scaffold-pattern.js';

const FIELDS = [
	'Title',
	'Slug',
	'Categories',
	'Keywords',
	'Template Types',
	'Description',
];

/**
 * Reads the wordpress.org file header of one pattern.
 *
 * @param {string} source Pattern file contents.
 * @return {Object<string,string>} Field => value.
 */
export function readHeader( source ) {
	const header = {};
	for ( const field of FIELDS ) {
		const match = new RegExp( `^ \\* ${ field }: (.+)$`, 'm' ).exec(
			source
		);
		header[ field ] = match ? match[ 1 ].trim() : '';
	}
	return header;
}

/**
 * Builds the Markdown document for a list of headers.
 *
 * @param {Array<Object<string,string>>} headers Pattern headers.
 * @return {string} Markdown.
 */
export function render( headers ) {
	const lines = [
		'# Patterns',
		'',
		`Generated by \`npm run docs:patterns\` from the file headers in \`patterns/\`: ${ headers.length } patterns in ${ CATEGORIES.length } categories. Patterns with a template type appear in the editor's new-page chooser.`,
		'',
	];
	for ( const category of CATEGORIES ) {
		const rows = headers
			.filter( ( h ) =>
				h.Categories.split( ',' )
					.map( ( c ) => c.trim() )
					.includes( `keel/${ category }` )
			)
			.sort( ( a, b ) => a.Title.localeCompare( b.Title ) );
		if ( rows.length === 0 ) {
			continue;
		}
		lines.push( `## keel/${ category } (${ rows.length })`, '' );
		lines.push(
			'| Title | Slug | Keywords | Template types |',
			'| --- | --- | --- | --- |'
		);
		for ( const row of rows ) {
			lines.push(
				`| ${ row.Title } | \`${ row.Slug }\` | ${ row.Keywords } | ${ row[ 'Template Types' ] || '' } |`
			);
		}
		lines.push( '' );
	}
	return lines.join( '\n' );
}

const headers = readdirSync( 'patterns' )
	.filter( ( file ) => file.endsWith( '.php' ) )
	.map( ( file ) =>
		readHeader( readFileSync( join( 'patterns', file ), 'utf8' ) )
	);
writeFileSync( 'docs/patterns.md', render( headers ) );
process.stdout.write( `docs/patterns.md (${ headers.length } patterns)\n` );
